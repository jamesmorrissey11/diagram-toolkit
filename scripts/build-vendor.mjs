// Regenerates engine/vendor/* from pinned upstream sources. Run: npm install && npm run build:vendor
//  - router.mjs            OpenDiagram packages/harness/src/router (Apache-2.0, commit 6cf306a, last pre-AGPL)
//  - excalidraw-render.js  @excalidraw/excalidraw@0.18.1 exportToSvg page bundle (MIT)
//  - fonts/                Excalidraw font assets used by the presets
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { cp, mkdir, rm, writeFile, readFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const VENDOR = path.join(ROOT, "skills/arch-diagram/engine/vendor");
const CACHE = path.join(ROOT, ".cache");
const OD_SHA = "6cf306aed655f167e472d4a61e41d90ca5fd0707";
const FONTS = ["Liberation", "Nunito", "Excalifont"];

await mkdir(CACHE, { recursive: true });
const od = path.join(CACHE, `OpenDiagram-${OD_SHA}`);
try { await stat(od); } catch {
  const tgz = path.join(CACHE, "od.tgz");
  execFileSync("curl", ["-sfL", `https://codeload.github.com/Itz-Agasta/OpenDiagram/tar.gz/${OD_SHA}`, "-o", tgz]);
  execFileSync("tar", ["-xzf", tgz, "-C", CACHE]);
}
const odLicense = await readFile(path.join(od, "LICENSE"), "utf8");
if (!/Apache License/.test(odLicense)) throw new Error("OpenDiagram LICENSE at pinned commit is not Apache-2.0");

await rm(VENDOR, { recursive: true, force: true });
await mkdir(path.join(VENDOR, "fonts"), { recursive: true });

await build({
  stdin: { contents: `export { routeEdges } from "./packages/harness/src/router/index.ts";`, resolveDir: od, loader: "ts" },
  bundle: true, platform: "node", format: "esm", outfile: path.join(VENDOR, "router.mjs"), logLevel: "error",
  banner: { js: `// Vendored from Itz-Agasta/OpenDiagram@${OD_SHA} packages/harness/src/router (Apache-2.0). See LICENSE-OpenDiagram.\n// Generated by scripts/build-vendor.mjs; do not edit.` },
});
await writeFile(path.join(VENDOR, "LICENSE-OpenDiagram"), odLicense);

await build({
  entryPoints: [path.join(ROOT, "scripts/render-entry.js")], bundle: true, format: "iife", minify: true,
  outfile: path.join(VENDOR, "excalidraw-render.js"), logLevel: "error",
  define: { "process.env.NODE_ENV": '"production"', "import.meta.env": "{}" },
  banner: { js: "/* @excalidraw/excalidraw@0.18.1 exportToSvg bundle (MIT, see LICENSE-Excalidraw). Generated by scripts/build-vendor.mjs */" },
});
const exc = path.join(ROOT, "node_modules/@excalidraw/excalidraw");
const excPkg = JSON.parse(await readFile(path.join(exc, "package.json"), "utf8"));
if (excPkg.version !== "0.18.1") throw new Error(`expected @excalidraw/excalidraw 0.18.1, got ${excPkg.version}`);
for (const f of FONTS) await cp(path.join(exc, "dist/prod/fonts", f), path.join(VENDOR, "fonts", f), { recursive: true });
const excLicense = await fetch("https://raw.githubusercontent.com/excalidraw/excalidraw/master/LICENSE").then((r) => r.text());
await writeFile(path.join(VENDOR, "LICENSE-Excalidraw"), excLicense);

const fi = await readFile(path.join(ROOT, "node_modules/fractional-indexing/src/index.js"), "utf8");
await writeFile(path.join(VENDOR, "fractional-indexing.mjs"), `// Vendored fractional-indexing@4.0.0 (CC0-1.0). Generated by scripts/build-vendor.mjs; do not edit.\n${fi}`);
console.log("vendor rebuilt:", VENDOR);
