// spec -> validate -> resolve preset/icons -> measure -> place -> route -> emit -> lint -> render
import { readFile, writeFile, mkdir, stat } from "node:fs/promises";
import path from "node:path";
import { normalizeSpec, loadPreset, SpecError } from "./spec.mjs";
import { buildGeometry, textsNeeded } from "./geometry.mjs";
import { placeGrid } from "./place.mjs";
import { route } from "./route.mjs";
import { emitScene } from "./emit.mjs";
import { lintScene } from "./lint.mjs";
import { embedMeta, editState, readMeta } from "./meta.mjs";
import { isBoard, normalizeBoardSpec, loadBoardPreset } from "./board-spec.mjs";
import { layoutBoard } from "./board-layout.mjs";
import { emitBoard } from "./board-emit.mjs";
import { lintBoard } from "./board-lint.mjs";

export class HandEditError extends Error {}

const exists = async (p) => { try { await stat(p); return true; } catch { return false; } };
export const outBaseOf = (specPath, out) => {
  if (out) return out.replace(/\.(excalidraw|png|svg)$/i, "");
  return specPath.replace(/(\.spec)?\.json$/i, "");
};

async function guardTarget(target, force) {
  if (!force && (await exists(target))) {
    const prev = JSON.parse(await readFile(target, "utf8"));
    const es = editState(prev);
    if (es.state === "edited")
      throw new HandEditError(`${target} was edited by hand since it was generated; regenerating would replace those edits. ` +
        `Re-run with --force to overwrite, or --out <new-file> to keep both.`);
    if (es.state === "foreign")
      throw new HandEditError(`${target} exists and was not generated by diagram-toolkit; use --force to overwrite or --out <new-file>.`);
  }
  await mkdir(path.dirname(path.resolve(target)), { recursive: true });
}

const idHintOf = (specPath) => path.basename(specPath).replace(/(\.spec)?\.json$/i, "");

export async function buildDiagram(studio, opts) {
  const raw = JSON.parse(await readFile(opts.specPath, "utf8"));
  if (isBoard(raw)) return buildBoard(studio, raw, opts);
  if (raw && raw.kind !== undefined && raw.kind !== "graph")
    throw new SpecError([`kind must be "board" or omitted for an architecture graph (got ${JSON.stringify(raw.kind)})`]);
  return buildGraph(studio, raw, opts);
}

async function buildGraph(studio, raw, { specPath, out, preset: requested, publish = false, force = false, scale = 2 }) {
  const t0 = Date.now();
  const { spec, presetSource } = normalizeSpec(raw, { requestedPreset: requested, idHint: path.basename(specPath).replace(/(\.spec)?\.json$/i, "") });
  const preset = await loadPreset(spec.preset);
  const base = outBaseOf(specPath, out);
  const target = `${base}.excalidraw`;
  await guardTarget(target, force);
  const t1 = Date.now();
  const tw = await studio.measure(preset, textsNeeded(spec, preset));
  const geo = buildGeometry(spec, preset, tw);
  const t2 = Date.now();
  const placed = placeGrid(spec, geo, preset);
  const routed = route(spec, geo, placed, preset);
  const t3 = Date.now();
  const { scene, issues } = await emitScene(spec, preset, geo, placed, routed);
  const lint = lintScene(scene, spec, preset, { publish });
  if (routed.fallbacks.length) lint.warnings.push(`router could not find clean paths for: ${routed.fallbacks.join(", ")}`);
  embedMeta(scene, spec, { preset: preset.name, presetSource, pass: lint.pass });
  await writeFile(target, JSON.stringify(scene, null, 1));
  const t4 = Date.now();
  const rendered = await studio.render(scene, base, { scale });
  const summary = {
    ok: lint.pass, preset: preset.name, presetSource, mode: publish ? "publish" : "draft",
    files: { excalidraw: target, png: rendered.png, svg: rendered.svg },
    hard: lint.hard, warnings: lint.warnings, issues, readability: lint.readability, advisory: lint.advisory,
    timings: { measureMs: t2 - t1, layoutMs: t3 - t2, emitLintMs: t4 - t3, renderMs: Date.now() - t4, totalMs: Date.now() - t0 },
  };
  await writeFile(`${base}.lint.json`, JSON.stringify(summary, null, 1));
  return summary;
}

async function buildBoard(studio, raw, { specPath, out, preset: requested, publish = false, force = false, scale = 2 }) {
  const t0 = Date.now();
  const { spec, presetSource } = normalizeBoardSpec(raw, { requestedPreset: requested, idHint: idHintOf(specPath) });
  const preset = await loadBoardPreset(spec.preset);
  const base = outBaseOf(specPath, out);
  const target = `${base}.excalidraw`;
  await guardTarget(target, force);
  const t1 = Date.now();
  const layout = await layoutBoard(spec, preset, (items) => studio.measure(preset, items));
  const t2 = Date.now();
  const scene = emitBoard(spec, preset, layout);
  const lint = lintBoard(scene, spec, preset, { fitColumns: layout.fitColumns });
  embedMeta(scene, spec, { preset: preset.name, presetSource, pass: lint.pass });
  await writeFile(target, JSON.stringify(scene, null, 1));
  const t3 = Date.now();
  const rendered = await studio.render(scene, base, { scale });
  const summary = {
    ok: lint.pass, kind: "board", preset: spec.preset, presetSource, mode: publish ? "publish" : "draft",
    files: { excalidraw: target, png: rendered.png, svg: rendered.svg },
    hard: lint.hard, warnings: lint.warnings, issues: [], readability: lint.readability, advisory: lint.advisory,
    layout: { columns: layout.columns, fitColumns: layout.fitColumns, columnWidth: layout.colW },
    timings: { layoutMs: t2 - t1, emitLintMs: t3 - t2, renderMs: Date.now() - t3, totalMs: Date.now() - t0 },
  };
  await writeFile(`${base}.lint.json`, JSON.stringify(summary, null, 1));
  return summary;
}

export async function lintFile(file, { publish = false } = {}) {
  const scene = JSON.parse(await readFile(file, "utf8"));
  const meta = readMeta(scene);
  if (!meta) throw new SpecError([`${file} has no embedded diagram-toolkit spec; lint only works on toolkit-generated files`]);
  if (meta.spec.kind === "board") {
    const lint = lintBoard(scene, meta.spec, await loadBoardPreset(meta.spec.preset));
    return { ok: lint.pass, edit: editState(scene).state, ...lint };
  }
  const preset = await loadPreset(meta.spec.preset);
  const lint = lintScene(scene, meta.spec, preset, { publish });
  return { ok: lint.pass, edit: editState(scene).state, ...lint };
}

export async function specOf(file) {
  const meta = readMeta(JSON.parse(await readFile(file, "utf8")));
  if (!meta) throw new SpecError([`${file} has no embedded diagram-toolkit spec`]);
  return meta.spec;
}
